"""Presentation-only localization. Data, NASA values and model keys remain unchanged."""
from i18n import t, month_name

FORECAST_COLUMNS = ('Date','Rain (mm)','Rain chance (%)','Reference ET0 (mm)','Field check')
FORECAST_STATUSES = (
    'Check local conditions',
    'Rain possible — check forecast before watering',
    'Check soil moisture before deciding to irrigate',
)
MONITOR_COLUMNS = ('Month','Mean rainfall (mm)','Mean temperature (°C)',
                   'Dry days (%)','Monitoring context','Years used')
MONITOR_STATUSES = ('Higher dry-day frequency','Moderate dry-day frequency','Lower dry-day frequency')

def localize_table(frame, *, known_statuses=(), localize_months=False):
    """Translate UI labels and known generated categories, not farmer-entered values."""
    result = frame.copy()
    # Month is a displayed value generated by the climate model, not a model key.
    if localize_months and 'Month' in result.columns:
        result['Month'] = result['Month'].map(lambda x: t(x) if isinstance(x, str) else x)
    for column in result.columns:
        if column in ('Field check', 'Monitoring context'):
            allowed = set(known_statuses)
            result[column] = result[column].map(lambda x: t(x) if isinstance(x,str) and x in allowed else x)
    result = result.rename(columns={c: t(c) for c in result.columns if isinstance(c, str)})
    return result
